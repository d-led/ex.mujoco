defmodule ExMujoco.Gen.Template do
  @moduledoc """
  The text this package generates, from the shapes `ExMujoco.Gen` hands it.

  Kept apart from the reading and the deciding so that what a generated binding
  looks like can be read in one place. Every emitted body is small on purpose: a
  field is one `return` and one `FINE_NIF`, a function is one call, and the only
  arithmetic anywhere is a dimension.

  `c_src/ex_mujoco_nif.cpp` is *not* generated. The parts that need a decision
  per call — an error buffer, an output array, a state signature — are written
  out by hand and listed in `c_src/manifest.exs`.
  """

  @reserved ~w(do end fn in not and or when after else catch rescue true false nil)

  # ------------------------------------------------------------------ Elixir

  @doc "The `Native` module this emits — one stub per generated NIF, and the load hook."
  def native(structs, functions, manifest) do
    stubs =
      Enum.map(fields_of(structs), &field_stub/1) ++
        Enum.map(bound_functions(functions, manifest), &function_stub/1) ++
        Enum.map(manifest.hand_written, &hand_stub/1)

    """
    # Generated by `mix ex_mujoco.gen`. Do not edit.
    #
    # One NIF per C function and per field of mjModel and mjData, at the arity the
    # C function has. Nothing here is meant to be called directly: the typed
    # wrappers are `ExMujoco`, `ExMujoco.Model` and `ExMujoco.Data`. The stubs
    # exist so that a name MuJoCo moves is a compile error here, rather than a
    # call that raises `:nif_not_loaded` in a test six months later.
    defmodule ExMujoco.Native do
      @moduledoc false

      @on_load :load

      # `:erlang.load_nif` only loads a library whose `ERL_NIF_INIT` name is this
      # module's, so the call has to be here. Whether the library and the headers
      # the NIF was generated from are the same version is `ExMujoco.Loader`'s
      # question, asked on first use — asking it here would mean calling this
      # module while it is still loading, which Erlang does not allow.
      @doc false
      def load do
        priv = :code.priv_dir(:ex_mujoco) |> to_string()

        # Windows will not look beside a library for the libraries it imports,
        # so MuJoCo has to be in the process before this one is loaded. On macOS
        # and Linux this answers `:ok` and does nothing.
        preload = ExMujoco.Preload.mujoco(priv)

        case :erlang.load_nif(:filename.join(priv, ~c"ex_mujoco_nif"), 0) do
          :ok ->
            :ok

          {:error, reason} ->
            {:error,
             "ex_mujoco: could not load the NIF: \#{inspect(reason)}" <> and_preload(preload)}
        end
      end

      defp and_preload(:ok), do: ""

      defp and_preload({:error, complaint}) do
        ", and MuJoCo itself: \#{complaint}"
      end

    #{indent(Enum.join(stubs, "\n"))}
    end
    """
  end

  defp field_stub(field) do
    nif(nil, nil, ["_" <> field.scope], nif_name(field))
  end

  defp function_stub(function) do
    nif(nil, nil, Enum.map(function.parameters, &parameter_name/1), function.name)
  end

  defp nif(_scope, _field, args, name) do
    """
    def #{name}(#{Enum.join(args, ", ")}), do: :erlang.nif_error(:nif_not_loaded)
    """
  end

  # The stubs are placeholders the NIF replaces, so their arguments are unused
  # by definition — and a warning nobody can act on is a warning that hides the
  # ones they can.
  # A hand-written NIF gets the same treatment: a stub, so that a name the C++
  # no longer registers is a load error naming the function.
  defp hand_stub(%{name: name, arity: arity}) do
    args =
      if arity == 0,
        do: [],
        else: Enum.map(1..arity, &("_" <> "argument" <> Integer.to_string(&1)))

    nif(nil, nil, args, name)
  end

  defp parameter_name(parameter) do
    case parameter.name do
      "" -> "_argument"
      name -> "_" <> safe_name(name)
    end
  end

  @doc "`ExMujoco.Model` or `ExMujoco.Data` — a typed reader per field."
  def fields(entity, scope, members) do
    readers =
      members
      |> Enum.filter(&(exposed?(&1) and &1.kind in [:integer, :float, :array]))
      |> Enum.map(&field_reader(scope, &1))

    """
    # Generated by `mix ex_mujoco.gen`. Do not edit.
    defmodule ExMujoco.#{entity} do
      @moduledoc \"\"\"
      The fields of `mj#{entity}`, read one at a time.

      Each function is one call into MuJoCo that copies the field out, so the
      answer is a value: it does not change under you when the next step runs.

        * a scalar answers a number — `#{example_scalar(members)}/1` answers
          #{example_scalar_kind(members)};
        * an array answers an `ExMujoco.Tensor`, with the element type and the
          shape, because a bare binary would have lost both;
        * a field MuJoCo gives no extent to is not here at all, and
          `docs/coverage.md` says which, and why.

      The functions are grouped under the heading MuJoCo's header gives the
      block they are declared in — `bodies`, `geoms`,
      `computed by mj_fwdPosition/mj_kinematics` — so the page reads in the
      order MuJoCo writes it, and the words are MuJoCo's.

      The names are MuJoCo's own — `geom_pos`, `qpos`, `efc_force` — so the
      documentation for a field is MuJoCo's documentation for that field.
      \"\"\"

      alias ExMujoco.{Native, Tensor}

      @typedoc "An mj#{entity} this process holds."
      @type t :: reference()

    #{indent(Enum.join(readers, "\n"))}
    end
    """
  end

  defp example_scalar(members) do
    case Enum.find(members, &(&1.kind in [:integer, :float])) do
      nil -> "nq"
      member -> safe_name(member.name)
    end
  end

  defp example_scalar_kind(members) do
    case Enum.find(members, &(&1.kind in [:integer, :float])) do
      %{kind: :float} -> "a float"
      _ -> "an integer"
    end
  end

  defp field_reader(scope, %{kind: :integer} = member) do
    """
    #{doc(member, "`#{member.c_type}` in C, read as an integer.")}
    @spec #{safe_name(member.name)}(t()) :: integer()
    def #{safe_name(member.name)}(#{scope}), do: Native.#{scope}_#{safe_name(member.name)}(#{scope})
    """
  end

  defp field_reader(scope, %{kind: :float} = member) do
    """
    #{doc(member, "`#{member.c_type}` in C, read as a float.")}
    @spec #{safe_name(member.name)}(t()) :: float()
    def #{safe_name(member.name)}(#{scope}), do: Native.#{scope}_#{safe_name(member.name)}(#{scope})
    """
  end

  defp field_reader(scope, %{kind: :array, element: {tag, _}} = member) do
    {rows, cols} = member.dims

    """
    #{doc(member, "`#{member.c_type}` in C, `#{rows}` × `#{cols}`.")}
    @spec #{safe_name(member.name)}(t()) :: ExMujoco.Tensor.t()
    def #{safe_name(member.name)}(#{scope}) do
      {data, rows, cols} = Native.#{scope}_#{safe_name(member.name)}(#{scope})
      Tensor.new(#{inspect(tag)}, {rows, cols}, data)
    end
    """
  end

  @doc false
  def doc(member, extra) do
    summary =
      case one_line(member.doc) do
        "" -> "`#{member.name}`."
        text -> "`#{member.name}` — #{text}"
      end

    """
    @doc \"\"\"
    #{summary}

    #{extra}
    \"\"\"
    #{group(member)}
    """
  end

  # MuJoCo's heading for the block the field is declared under. The heading is a
  # comment in MuJoCo's header, so `bodies` and
  # `computed by mj_fwdPosition/mj_kinematics` are MuJoCo's words for what the
  # fields below them are, not ours — and every field has one.
  defp group(%{section: section}) when is_binary(section),
    do: "@doc group: \"#{escape(section)}\""

  defp group(_member), do: ""

  # ------------------------------------------------------------------ C++

  @doc "The field accessors, as NIFs."
  def field_nifs(structs) do
    names = member_names(structs)

    body =
      structs
      |> fields_of()
      |> Enum.map(&field_nif(&1, names))
      |> Enum.reject(&(&1 == ""))

    """
    // Generated by `mix ex_mujoco.gen`. Do not edit.
    //
    // One NIF per field. The value is copied out here, so nothing handed to Elixir
    // aliases live mjData. An array's extent comes from the same X-macro list
    // MuJoCo uses to size its own scene, so the `ngeom` in `geom_pos[ngeom × 3]`
    // is the model's. `m` is the model the accessor reads; for a Data accessor it
    // is the model the Data was made from, which is why mjData needs no sizes of
    // its own.
    #{Enum.join(body, "\n")}
    """
  end

  # A scalar belongs to the struct that declares it: `d->pstack`, not `m->pstack`.
  defp owner(%{scope: "model"}), do: "m"
  defp owner(%{scope: "data"}), do: "d"

  defp field_nif(%{kind: :integer} = field, _names) do
    """
    int64_t #{nif_name(field)}(ErlNifEnv *, fine::ResourcePtr<exmujoco::#{field.entity}> #{field.scope}) {
      #{locals(field)}
      return static_cast<int64_t>(#{owner(field)}->#{field.name});
    }
    FINE_NIF(#{nif_name(field)}, 0);
    """
  end

  defp field_nif(%{kind: :float} = field, _names) do
    """
    double #{nif_name(field)}(ErlNifEnv *, fine::ResourcePtr<exmujoco::#{field.entity}> #{field.scope}) {
      #{locals(field)}
      return static_cast<double>(#{owner(field)}->#{field.name});
    }
    FINE_NIF(#{nif_name(field)}, 0);
    """
  end

  defp field_nif(%{kind: :array, element: {_tag, c_type}} = field, names) do
    {rows, cols} = field.dims

    """
    // #{one_line(field.doc)}
    std::tuple<fine::Term, int64_t, int64_t> #{nif_name(field)}(ErlNifEnv *env, fine::ResourcePtr<exmujoco::#{field.entity}> #{field.scope}) {
      #{locals(field)}
      const size_t rows = #{dim(field, rows, names)};
      const size_t cols = #{dim(field, cols, names)};
      return {fine::make_new_binary(env, reinterpret_cast<const char *>(#{owner(field)}->#{field.name}),
                sizeof(#{c_type}) * rows * cols),
              static_cast<int64_t>(rows), static_cast<int64_t>(cols)};
    }
    FINE_NIF(#{nif_name(field)}, 0);
    """
  end

  # The model is `m` in both accessors: mjData does not point at its model, so the
  # Data resource carries it, and a data field dimensioned by `nq` reads the
  # model's `nq`.
  defp locals(%{scope: "model"}), do: "[[maybe_unused]] auto *m = model->model;"

  defp locals(%{scope: "data"}),
    do: "[[maybe_unused]] auto *m = data->model->model;\n  [[maybe_unused]] auto *d = data->data;"

  # A dimension is a number, a member of one of the two structs, or a C macro
  # (`mjNISLAND*mjNSOLVER`). Which struct a bare name belongs to is decided by
  # looking it up: `mjxmacro.h` says a bare name is a model member "by default",
  # and mjData does not carry the model's sizes.
  defp dim(_field, "1", _names), do: "1"

  # A dimension is a number, a member of one of the two structs (`ngeom`,
  # `nkey`, `MJ_M(nmocap)*3`), or a C macro (`mjNISLAND*mjNSOLVER`). Every
  # identifier is looked up, because a dimension can be an expression and only
  # some of its names are members. `mjxmacro.h` says a bare name is a model
  # member "by default"; mjData does not carry the model's sizes, so a data
  # accessor reaches them through the model its handle holds.
  defp dim(_field, expression, names) do
    Regex.replace(~r/([A-Za-z_][A-Za-z0-9_]*)(@model|@data)?/u, expression, fn _, name, marker ->
      cond do
        marker == "@model" -> "m->" <> name
        marker == "@data" -> "d->" <> name
        MapSet.member?(names.model, name) -> "m->" <> name
        MapSet.member?(names.data, name) -> "d->" <> name
        true -> name
      end
    end)
  end

  @doc "The bound functions, as C++ NIFs."
  def function_nifs(functions, manifest) do
    body =
      functions
      |> bound_functions(manifest)
      |> Enum.map(&function_nif/1)

    """
    // Generated by `mix ex_mujoco.gen`. Do not edit.
    //
    // One NIF per bound function, and every body is one call. `exmujoco::call`
    // turns MuJoCo's fatal error — which would otherwise abort the VM — into an
    // Elixir exception.
    #{Enum.join(body, "\n")}
    """
  end

  defp function_nif(function) do
    params =
      Enum.map_join(function.parameters, ", ", fn parameter ->
        "#{cpp_parameter_type(parameter)} #{cpp_name(parameter)}"
      end)

    arguments = Enum.map_join(function.parameters, ", ", &cpp_argument/1)

    signature = "#{function.name}(#{join_head(params)})"
    call = "::#{function.name}(#{arguments})"

    case return_kind(function.returns) do
      :void ->
        # Fine's `nif_impl` stores the answer in a local, so a NIF cannot return
        # `void`; MuJoCo's `void` means "it worked, ask the data", which is `:ok`.
        """
        // #{one_line(function.doc)}
        fine::Atom #{signature} {
          exmujoco::call([&] { #{call}; });
          return exmujoco::ok();
        }
        FINE_NIF(#{function.name}, 0);
        """

      :string ->
        """
        // #{one_line(function.doc)}
        std::optional<std::string> #{signature} {
          const char *answer = exmujoco::call([&] { return #{call}; });
          if (answer == nullptr) return std::nullopt;
          return std::string(answer);
        }
        FINE_NIF(#{function.name}, 0);
        """

      type ->
        """
        // #{one_line(function.doc)}
        #{type} #{signature} {
          return exmujoco::call([&] { return #{call}; });
        }
        FINE_NIF(#{function.name}, 0);
        """
    end
  end

  defp join_head(""), do: "ErlNifEnv *env"
  defp join_head(params), do: "ErlNifEnv *env, " <> params

  defp cpp_parameter_type(%{kind: :integer}), do: "int64_t"
  defp cpp_parameter_type(%{kind: :float}), do: "double"
  defp cpp_parameter_type(%{kind: :string}), do: "std::string"
  defp cpp_parameter_type(%{kind: :buffer}), do: "ErlNifBinary"

  defp cpp_parameter_type(%{kind: :resource, type: %{name: "mjModel"}}),
    do: "fine::ResourcePtr<exmujoco::Model>"

  defp cpp_parameter_type(%{kind: :resource, type: %{name: "mjData"}}),
    do: "fine::ResourcePtr<exmujoco::Data>"

  defp cpp_name(parameter), do: parameter.name |> safe_name()

  defp cpp_argument(%{kind: kind, type: type, name: name}) when kind in [:integer, :float],
    do: "static_cast<#{type.name}>(#{safe_name(name)})"

  defp cpp_argument(%{kind: :string, name: name}), do: "#{safe_name(name)}.c_str()"

  defp cpp_argument(%{kind: :resource, type: %{name: "mjModel"}, name: name}),
    do: "#{safe_name(name)}->model"

  defp cpp_argument(%{kind: :resource, type: %{name: "mjData"}, name: name}),
    do: "#{safe_name(name)}->data"

  defp cpp_argument(%{kind: :buffer, type: type, name: name}),
    do: "reinterpret_cast<const #{type.name} *>(#{safe_name(name)}.data)"

  defp return_kind(%{name: "void", pointers: 0}), do: :void
  defp return_kind(%{name: "char", pointers: 1, const: true}), do: :string

  defp return_kind(%{name: name, pointers: 0})
       when name in ["mjtNum", "double", "float"],
       do: "double"

  defp return_kind(%{name: name, pointers: 0})
       when name in ["int", "mjtSize", "size_t", "uintptr_t", "mjtBool", "mjtByte"],
       do: "int64_t"

  defp return_kind(_other), do: :unsupported

  # ------------------------------------------------------------------ api

  @doc "`ExMujoco.Api` — the C functions bound 1:1, under their C names."
  def api(functions, manifest) do
    wrappers = Enum.map_join(bound_functions(functions, manifest), "\n", &api_wrapper/1)

    """
    # Generated by `mix ex_mujoco.gen`. Do not edit.
    defmodule ExMujoco.Api do
      @moduledoc \"\"\"
      MuJoCo's own functions, bound one for one, under the names MuJoCo gives
      them.

      These are the calls that speak for themselves — \`mj_name2id\`,
      \`mj_kinematics\`, \`mj_step1\` — so the binding is the C signature and
      nothing more, and the argument order and meaning are MuJoCo's. The curated
      surface is \`ExMujoco\`, which is what most callers want: it names the data
      block once and answers \`:ok\`, an \`ExMujoco.Tensor\`, or an
      \`ExMujoco.Error\`.

      The sentence under each name is MuJoCo's own comment on the declaration,
      and the functions are filed under the heading MuJoCo's header puts above
      them — \`Main simulation\`, \`Sub components\`, \`Support\` — so the page
      reads as MuJoCo's header does.

      What is *not* here is in \`docs/coverage.md\`, with the reason.
      \"\"\"

      alias ExMujoco.Native

    #{indent(wrappers)}
    end
    """
  end

  defp api_wrapper(function) do
    args = Enum.map(function.parameters, &safe_name(&1.name))

    """
    #{api_doc(function)}
    def #{function.name}(#{Enum.join(args, ", ")}), do: Native.#{function.name}(#{Enum.join(args, ", ")})
    """
  end

  # MuJoCo writes a line of prose above each declaration and a `// ---- Section
  # ----` line above runs of them. Both are copied, so the page says what the C
  # says and files a function where MuJoCo files it.
  defp api_doc(function) do
    summary =
      case one_line(function.doc) do
        "" -> "`#{function.name}` — `#{c_signature(function)}`"
        prose -> "`#{function.name}` — #{prose}\n\n`#{c_signature(function)}` in C."
      end

    """
    @doc \"\"\"
    #{summary}
    \"\"\"
    #{group(function)}
    """
  end

  defp c_signature(function) do
    params =
      Enum.map_join(function.parameters, ", ", fn parameter ->
        name = if parameter.name == "", do: "", else: " #{parameter.name}"
        "#{parameter.type.name}#{String.duplicate("*", parameter.type.pointers)}#{name}"
      end)

    "#{function.returns.name}#{String.duplicate("*", function.returns.pointers)} #{function.name}(#{params})"
  end

  # ------------------------------------------------------------------ enums

  @doc "One module per enum, under `ExMujoco.Types`."
  def enum_modules(enums) do
    Map.new(enums, fn enum -> {enum_path(enum), enum_module(enum)} end)
  end

  defp enum_module(enum) do
    module = enum_module_name(enum)
    prefix = common_prefix(enum.items)
    {numbered, unnumbered} = Enum.split_with(enum.items, &(&1.value != nil))

    functions =
      Enum.map_join(numbered, "\n", fn item ->
        name = item_function_name(item.name, prefix)

        """
        @doc "#{item.name} is #{item.value}."
        @spec #{name}() :: #{item.value}
        def #{name}, do: #{item.value}
        """
      end)

    values =
      Enum.map_join(numbered, ",\n", fn item ->
        "      {#{inspect(atom_name(item.name, prefix))}, #{item.value}}"
      end)

    """
    # Generated by `mix ex_mujoco.gen`. Do not edit.
    defmodule #{module} do
      @moduledoc "`#{enum.name}`, from MuJoCo's headers, as numbers. #{doc_summary(enum, unnumbered)}"

      @type t :: integer()

    #{indent(functions)}
      @doc "Every value, as `{name, integer}`, in the order the header lists them."
      @spec values() :: [{atom(), integer()}]
      def values do
        [
    #{values}
        ]
      end

      @doc "The integer behind a name. An integer is already one."
      @spec to_integer(t() | atom()) :: integer() | nil
      def to_integer(value) when is_integer(value), do: value
      def to_integer(value) when is_atom(value), do: Keyword.get(values(), value)

      @doc "The name behind an integer. An atom is already one."
      @spec to_atom(integer() | atom()) :: atom() | nil
      def to_atom(value) when is_atom(value), do: value

      def to_atom(value) when is_integer(value),
        do: Enum.find_value(values(), fn {name, number} -> if number == value, do: name end)
    end
    """
  end

  defp doc_summary(enum, []) do
    "All #{length(enum.items)} values carry a number in the header."
  end

  defp doc_summary(_enum, unnumbered) do
    "The #{length(unnumbered)} values the header gives no number to are not here: " <>
      "C numbers them, and a number this package invented would be a guess. " <>
      "docs/coverage.md lists them."
  end

  defp enum_path(enum), do: "lib/ex_mujoco/types/#{Macro.underscore(enum_short(enum))}.ex"

  defp enum_module_name(enum), do: "ExMujoco.Types." <> Macro.camelize(enum_short(enum))

  defp enum_short(enum), do: String.replace_prefix(enum.name, "mjt", "")

  # The prefix the items share — `mjGEOM_` for `mjGEOM_BOX` — taken from the items
  # themselves, because an enum's name does not always match them: `mjtDisableBit`
  # holds `mjDSBL_*`. The first item's token is used when more than half the items
  # carry it, which is what keeps a trailing sentinel like `mjNGEOMTYPES` — no
  # underscore, different token — from collapsing the prefix to `mj`.
  defp common_prefix([]), do: ""

  defp common_prefix(items) do
    names = Enum.map(items, & &1.name)
    prefix = (names |> hd() |> String.split("_") |> hd()) <> "_"

    if Enum.count(names, &String.starts_with?(&1, prefix)) * 2 > length(names),
      do: prefix,
      else: ""
  end

  defp item_function_name(name, prefix) do
    remainder = String.replace_prefix(name, prefix, "") |> String.downcase()

    if String.match?(remainder, ~r/^[a-z][a-z0-9_]*$/),
      do: safe_name(remainder),
      else: safe_name(String.downcase(name))
  end

  defp atom_name(name, prefix) do
    name
    |> String.replace_prefix(prefix, "")
    |> String.downcase()
    |> String.to_atom()
  end

  # ------------------------------------------------------------------ coverage

  @doc "What is bound, what is not, and why — as Markdown."
  def coverage(structs, functions, enums, manifest) do
    bound = functions |> bound_functions(manifest) |> Enum.map(& &1.name) |> MapSet.new()
    hand = manifest.hand_written |> Enum.map(& &1.name) |> MapSet.new()
    unbound = Enum.reject(functions, &expressible?/1)

    """
    # What is bound

    Generated by `mix ex_mujoco.gen` from MuJoCo's own headers. Regenerating is
    the only way to edit this page, and `mix ex_mujoco.gen --check` fails when it
    disagrees with the headers.

    ## Functions

    #{table([["MuJoCo functions", length(functions)], ["bound 1:1 by the generator", MapSet.size(bound)], ["bound by hand", MapSet.size(hand)], ["not bound", length(functions) - MapSet.size(bound) - MapSet.size(hand)]])}

    ### Bound by hand

    These need a decision per call — an error buffer to allocate, an output array
    whose length is the caller's business, a state signature — so they are written
    out in `c_src/ex_mujoco_nif.cpp` rather than generated.

    #{bullets(Enum.map(manifest.hand_written, fn %{name: name, arity: arity, why: why} -> "`#{name}/#{arity}` — #{why}" end))}

    ### Not bound

    #{length(unbound)} of MuJoCo's #{length(functions)} functions take something a
    NIF cannot honestly invent — a callback, a `void*`, an output array whose
    length nothing states, a variadic argument list — and binding one means
    deciding that question, one function at a time. The other
    #{length(functions) - length(unbound) - MapSet.size(bound) - MapSet.size(hand)}
    are expressible and simply not bound yet: a name in `c_src/manifest.exs`, and
    `mix ex_mujoco.gen`.

    #{notes(manifest)}

    ## Fields

    #{field_table(structs)}

    MuJoCo's own API reference describes each of them; the names and the units are
    MuJoCo's, and its documentation is the documentation for the field.

    ## Enums

    All #{length(enums)} enums MuJoCo declares are generated into `ExMujoco.Types`
    with the values resolved from the headers — including the ones C numbers
    implicitly and the ones that are an OR of their siblings.
    """
  end

  defp notes(%{notes: notes}) when notes == %{}, do: ""

  defp notes(%{notes: notes}) do
    "Decisions worth naming:\n\n" <>
      bullets(Enum.map(notes, fn {name, why} -> "`#{name}` — #{why}" end))
  end

  defp field_table(structs) do
    rows =
      for struct <- ["mjModel", "mjData"] do
        members = Map.fetch!(structs, struct)
        counts = Enum.frequencies_by(members, & &1.kind)

        [
          "`#{struct}`",
          Integer.to_string(Map.get(counts, :integer, 0) + Map.get(counts, :float, 0)),
          Integer.to_string(Map.get(counts, :array, 0) - unexposed_arrays(members)),
          Integer.to_string(Map.get(counts, :unsupported, 0) + unexposed_arrays(members))
        ]
      end

    table([["struct", "scalars", "arrays", "not exposed"] | rows])
  end

  defp unexposed_arrays(members),
    do: Enum.count(members, &(&1.kind == :array and &1.element == nil))

  defp table([header | rows]) do
    line = "| " <> Enum.join(header, " | ") <> " |"
    rule = "| " <> Enum.map_join(header, " | ", fn _ -> "---" end) <> " |"
    body = Enum.map_join(rows, "\n", fn row -> "| " <> Enum.join(row, " | ") <> " |" end)
    Enum.join([line, rule, body], "\n")
  end

  defp bullets(lines), do: Enum.map_join(lines, "\n", &"* #{&1}")

