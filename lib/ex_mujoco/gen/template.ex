  defp bound_functions(functions, manifest) do
    wanted = MapSet.new(manifest.functions)

    Enum.filter(functions, &MapSet.member?(wanted, &1.name))
  end

  @doc """
  Whether a C function can be bound from its signature alone.

  The rules are the four questions a NIF has to answer: what to pass for a
  callback (nothing), what a `void*` is (anything), how long an output array is
  (the caller's business), and what a variadic list contains (unknown).
  """
  def expressible?(function) do
    not function.variadic and
      return_kind(function.returns) != :unsupported and
      Enum.all?(
        function.parameters,
        &(parameter_kind(&1) in [:integer, :float, :string, :resource, :buffer])
      )
  end

  @doc "Why a function cannot be bound, in a sentence."
  def unexpressible_reason(function) do
    cond do
      function.variadic ->
        "it is variadic, and a NIF has a fixed arity"

      return_kind(function.returns) == :unsupported ->
        "its return type is not one a NIF can answer"

      true ->
        Enum.find_value(function.parameters, "it is generated", &parameter_reason/1)
    end
  end

  defp parameter_reason(%{kind: :opaque, type: type}),
    do: "it takes a `#{type.name}` pointer that a NIF cannot honestly make up"

  defp parameter_reason(%{kind: :buffer, type: %{const: false}}),
    do: "it writes into a buffer whose length nothing states"

  defp parameter_reason(_parameter), do: nil

  # A writable buffer is an output array whose length nothing in the signature
  # states, which is the one thing a NIF cannot decide on the caller's behalf.
  defp parameter_kind(%{kind: :buffer, type: %{const: false}}), do: :opaque
  defp parameter_kind(%{kind: kind}), do: kind

  # One entry per bindable field, in the order the package declares its structs.
  defp fields_of(structs) do
    for struct <- ["mjModel", "mjData"],
        member <- Map.fetch!(structs, struct),
        exposed?(member),
        member.kind in [:integer, :float, :array] do
      %{
        entity: entity_for(struct),
        scope: scope_for(struct),
        name: member.name,
        kind: member.kind,
        dims: member.dims || {"1", "1"},
        element: member.element,
        doc: member.doc,
        c_type: member.c_type,
        pointers: member.pointers
      }
    end
  end

  # A scalar has no element type, an array has one, and an array without one is a
  # member MuJoCo does not dimension.
  defp exposed?(%{kind: :array, element: element}), do: element != nil
  defp exposed?(%{kind: kind}), do: kind != :unsupported

  defp member_names(structs) do
    %{
      model: MapSet.new(Enum.map(Map.fetch!(structs, "mjModel"), & &1.name)),
      data: MapSet.new(Enum.map(Map.fetch!(structs, "mjData"), & &1.name))
    }
  end

  defp entity_for("mjModel"), do: "Model"
  defp entity_for("mjData"), do: "Data"
  defp scope_for("mjModel"), do: "model"
  defp scope_for("mjData"), do: "data"

  # An Elixir function cannot start with a capital, and MuJoCo has fields that do
  # (`B_rownnz`, `M`, `qM`), so the leading letter is downcased. The C member is
  # still spelled as MuJoCo spells it — only the name Elixir calls it by changes.
  defp safe_name(name) do
    name = String.replace(name, ~r/[^A-Za-z0-9_]/u, "_")
    name = if String.match?(name, ~r/^[0-9]/), do: "_" <> name, else: name
    name = String.replace(name, ~r/^[A-Z]/u, &String.downcase/1)
    if name in @reserved, do: name <> "_", else: name
  end

  defp nif_name(field), do: "#{field.scope}_#{safe_name(field.name)}"

  defp one_line(text), do: text |> String.replace(~r/\s+/u, " ") |> String.trim() |> escape()

  # Everything here lands in a string literal in the generated module, so a
  # backslash, a quote or an interpolation opener in MuJoCo's prose is escaped
  # first — MuJoCo's headers are C comments, and a `#{` in one is a comment, not
  # code, until it is copied into Elixir source.
  defp escape(text) do
    text
    |> String.replace("\\", "\\\\")
    |> String.replace("\"", "\\\"")
    |> String.replace("\#{", "\\\#{")
  end

  defp indent(text) do
    text
    |> String.split("\n")
    |> Enum.map_join("\n", fn
      "" -> ""
      line -> "  " <> line
    end)
  end
end
